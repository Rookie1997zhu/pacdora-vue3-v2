/**
 * 「按尺寸插值」模板的把关：用没有参与插值的混合尺寸样本（三个维度同时变，docs/pacdora-multisize/<编号>_<a-d>.json）
 * 检验每个盒型，只把达标的留在索引 src/catalog/sampledIndex.js 里（索引里有的才会被启用）。
 *
 * 启用分两档（A/B = 面片数一致、展开尺寸 ≤2%、切线长度 ≤6%）：
 *   verified  采样范围内至少 2 个验证样本，且全部达到 A 或 B
 *   improved  范围内至少 3 个验证样本、只有 1 个不达标，且达标数多于原来的参数化模板
 * 不达标的数据文件只留存根（记录了退回用的参数化模板），不进索引，预设会被 apply-sampled-templates 改回原模板。
 * 在 build-sampled-templates.mjs 之后运行。输出明细 docs/按尺寸插值_验证结果.csv
 */
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {TEMPLATES} from '../src/templates/index.js'
import SAMPLED_INDEX from '../src/catalog/sampledIndex.js'
import {measure,gradeOf,sampleInput} from './check-pacdora-fidelity.mjs'
import {pickAnchor} from '../src/templates/sampled/sampledGeometry.js'

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const SAMPLES=path.join(ROOT,'docs','pacdora-multisize')
const pct=x=>(x*100).toFixed(1)+'%'
const allFiles=fs.existsSync(SAMPLES)?fs.readdirSync(SAMPLES):[]
const rows=[]
const kept={}
const verdicts={}

for(const t of Object.values(TEMPLATES).filter(x=>x.sampled)){
  const d=t.sampled
  const key=`${d.cat}-${d.num}`
  if(!SAMPLED_INDEX[key])continue
  let inRange=0,passed=0,total=0,specPassed=0
  const notes=[]
  // 验证样本：四组混合尺寸（_a.._d），以及每个次段各一个（_v<n>）
  const vfiles=allFiles.filter(x=>x.startsWith(`${d.num}_`)&&/_([a-d]|v\d+)\.json$/.test(x)).sort()
  for(const vf of vfiles){
    const v=vf.slice(d.num.length+1,-5)
    const f=path.join(SAMPLES,vf)
    total++
    const geom=JSON.parse(fs.readFileSync(f,'utf8'))
    const k=geom.knifeSize
    const within=!!pickAnchor(d,{L:Number(k.L),W:Number(k.W),H:Number(k.H)})
    const m=measure(t.id,geom,sampleInput(geom))
    const g=m.error?'E':gradeOf(m)
    if(within){inRange++;if(g==='A'||g==='B')passed++}
    // 同一批样本上，原来的参数化模板（默认参数）表现如何
    let sg=''
    if(d.fallback&&TEMPLATES[d.fallback]){
      const sm=measure(d.fallback,geom,sampleInput(geom))
      sg=sm.error?'E':gradeOf(sm)
      if(within&&(sg==='A'||sg==='B'))specPassed++
    }
    rows.push({key,名称:d.name,验证尺寸:[k.L,k.W,k.H].join('×'),在采样范围内:within?'是':'否',等级:g,
      展开尺寸偏差:m.error?'':pct(Math.max(m.sheetWErr,m.sheetHErr)),切线长度偏差:m.error?'':pct(m.cutErr),面片数:m.error?m.error:`${m.faces}/${m.refFaces}`,原模板等级:sg})
    notes.push(`${v}:${within?'':'外'}${g}`)
  }
  const segs=[d,...(d.anchors||[])]
  const span=x=>Math.max(...segs.map(a=>a.range[x][1]))/Math.max(1e-9,Math.min(...segs.map(a=>a.range[x][0])))
  // verified：范围内验证样本全部达标；improved：没有全部达标，但明显好于原来的参数化模板
  const quality=inRange>=2&&passed===inRange?'verified'
    :inRange>=3&&passed>=inRange-1&&passed>specPassed?'improved'
    :null
  const ok=!!quality
  verdicts[key]={ok,quality,inRange,passed,specPassed,total,范围:[d,...(d.anchors||[])].map(a=>`L${a.range.L.join('–')} W${a.range.W.join('–')} H${a.range.H.join('–')}`).join(' | '),段数:1+(d.anchors||[]).length,窄:['L','W','H'].filter(x=>span(x)<1.25).join('')}
  if(ok)kept[key]={hash:typeof SAMPLED_INDEX[key]==='string'?SAMPLED_INDEX[key]:SAMPLED_INDEX[key].hash,quality}
  console.log(ok?(quality==='verified'?'启用':'启用(改善)'):'不启用',key,`原模板 ${specPassed}/${inRange}`,notes.join(' '),verdicts[key].窄?`(范围窄: ${verdicts[key].窄})`:'')
}

const cols=['key','名称','验证尺寸','在采样范围内','等级','展开尺寸偏差','切线长度偏差','面片数','原模板等级']
const cell=v=>{const s=String(v??'');return /[",\n]/.test(s)?`"${s.replace(/"/g,'""')}"`:s}
fs.writeFileSync(path.join(ROOT,'docs','按尺寸插值_验证结果.csv'),'﻿'+[cols.join(',')].concat(rows.map(r=>cols.map(c=>cell(r[c])).join(','))).join('\n'))
fs.writeFileSync(path.join(ROOT,'docs','按尺寸插值_盒型结论.json'),JSON.stringify(verdicts,null,1))
fs.writeFileSync(path.join(ROOT,'src','catalog','sampledIndex.js'),`// generated by scripts/build-sampled-templates.mjs + validate-sampled-templates.mjs — do not edit\nexport default ${JSON.stringify(kept,null,1)}\n`)
// 没启用的盒型：数据文件只留一个存根（记着退回用的参数化模板）。完整的插值数据用不上，
// 分段多的盒型一个文件能有几 MB，留着只会撑大前端包；build-sampled-templates 每次都会从样本重新生成。
for(const [key,v] of Object.entries(verdicts)){
  if(v.ok)continue
  const f=path.join(ROOT,'public','sampled',`${key}.json`)
  if(!fs.existsSync(f))continue
  const d=JSON.parse(fs.readFileSync(f,'utf8'))
  fs.writeFileSync(f,JSON.stringify({schema:d.schema,cat:d.cat,num:d.num,name:d.name,fallback:d.fallback||null,enabled:false}))
}
const all=Object.values(verdicts)
console.log(`\n启用 ${Object.keys(kept).length} / ${all.length}；范围内验证样本 ${all.reduce((s,v)=>s+v.passed,0)}/${all.reduce((s,v)=>s+v.inRange,0)} 达标`)
