/**
 * 在缺少 pacdora_boxes_geom.csv 时，把 mapOverrides 写回 src/catalog/presets.js。
 * 有 CSV 时应优先跑 build-presets-from-csv.mjs（会读同一覆盖表）。
 */
import {readFileSync,writeFileSync,existsSync} from 'node:fs'
import {join,dirname} from 'node:path'
import {fileURLToPath} from 'node:url'

const root=join(dirname(fileURLToPath(import.meta.url)),'..')
const overridesPath=join(root,'src','catalog','mapOverrides.json')
const presetsPath=join(root,'src','catalog','presets.js')

if(!existsSync(overridesPath)){
  console.error('missing',overridesPath)
  process.exit(1)
}
if(!existsSync(presetsPath)){
  console.error('missing',presetsPath)
  process.exit(1)
}

const overrides=JSON.parse(readFileSync(overridesPath,'utf8'))
const manualPath=join(root,'src','catalog','mapOverrides.manual.json')
if(existsSync(manualPath)){
  Object.assign(overrides,JSON.parse(readFileSync(manualPath,'utf8')))
}
const raw=readFileSync(presetsPath,'utf8')
const data=JSON.parse(raw.replace(/^\/\*\*[\s\S]*?\*\/\s*export\s+default\s+/,'').trim())

let applied=0,already=0,missing=0
const byNum=Object.fromEntries((data.presets||[]).map(p=>[String(p.sourceNum),p]))

for(const [num,tid] of Object.entries(overrides)){
  const p=byNum[num]
  if(!p){missing++;continue}
  if(p.templateId===tid){already++;continue}
  p.templateId=tid
  p.templateSource='map-override'
  applied++
}

const byTemplate={},byCategory={}
let mapped=0
for(const p of data.presets||[]){
  const k=p.templateId||'unmapped'
  if(p.templateId)mapped++
  byTemplate[k]=(byTemplate[k]||0)+1
  byCategory[p.categoryId]=(byCategory[p.categoryId]||0)+1
}
data.mapped=mapped
data.byTemplate=byTemplate
data.byCategory=byCategory
if(Array.isArray(data.categories)){
  data.categories=data.categories.map(c=>({...c,count:byCategory[c.id]||0}))
}

writeFileSync(
  presetsPath,
  `/** auto-generated by scripts/build-presets-from-csv.mjs — do not edit */\nexport default ${JSON.stringify(data,null,2)}\n`
)

console.log(JSON.stringify({
  overrideKeys:Object.keys(overrides).length,
  applied,
  already,
  missing,
  mapped:data.mapped,
  count:data.count,
  byTemplate
},null,2))
