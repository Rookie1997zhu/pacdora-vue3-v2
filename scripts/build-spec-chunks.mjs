/**
 * 把结构规格拆成按盒型加载的文件，供浏览器端懒加载（src/templates/lazy.js）：
 *   public/spec/<code>.json            每份规格一个文件（只含预设用到的规格）
 *   src/catalog/structureSpecIndex.js  code → 内容哈希（进前端包，用于定位与缓存失效）
 * Node 端仍直接读 src/catalog/structureSpecs.js，全量注册。
 * 在 catalog-build 末尾运行（规格挂载完成之后）。
 */
import {readFileSync,writeFileSync,mkdirSync,readdirSync,rmSync,existsSync} from 'node:fs'
import {join,dirname} from 'node:path'
import {fileURLToPath} from 'node:url'
import {createHash} from 'node:crypto'
import specData from '../src/catalog/structureSpecs.js'
import {isExcludedPreset} from '../src/catalog/excludedPresets.js'

const root=join(dirname(fileURLToPath(import.meta.url)),'..')
const outDir=join(root,'public','spec')
const indexPath=join(root,'src','catalog','structureSpecIndex.js')

const raw=readFileSync(join(root,'src','catalog','presets.js'),'utf8')
// 已从目录排除的预设不算在内：它们用到的规格没有页面会加载（与 check-spec-chunks 的口径一致）
const presets=(JSON.parse(raw.replace(/^\/\*\*[\s\S]*?\*\/\s*export\s+default\s+/,'').trim()).presets||[]).filter(p=>!isExcludedPreset(p.id))
const used=new Set(presets.map(p=>p.templateId).filter(t=>typeof t==='string'&&t.startsWith('spec-')).map(t=>t.slice(5)))
// 「按尺寸插值」模板在采样范围之外退回的结构规格也要能懒加载
const sampledDir=join(root,'public','sampled')
if(existsSync(sampledDir)){
  for(const f of readdirSync(sampledDir)){
    if(!f.endsWith('.json'))continue
    try{const fb=JSON.parse(readFileSync(join(sampledDir,f),'utf8')).fallback;if(typeof fb==='string'&&fb.startsWith('spec-'))used.add(fb.slice(5))}catch{/* ignore */}
  }
}

mkdirSync(outDir,{recursive:true})
const keep=new Set()
const index={}
let bytes=0,max=0
for(const spec of specData.specs||[]){
  if(!used.has(spec.code))continue
  // 文件名即 code；只允许安全字符，避免路径问题
  if(!/^[A-Za-z0-9_.-]+$/.test(spec.code))throw new Error(`unsafe spec code: ${spec.code}`)
  const body=JSON.stringify(spec)
  const hash=createHash('sha256').update(body).digest('hex').slice(0,10)
  const file=`${spec.code}.json`
  writeFileSync(join(outDir,file),body)
  keep.add(file)
  index[spec.code]=hash
  bytes+=body.length
  max=Math.max(max,body.length)
}
// 清掉不再使用的旧文件
let removed=0
if(existsSync(outDir)){
  for(const f of readdirSync(outDir)){
    if(f.endsWith('.json')&&!keep.has(f)){rmSync(join(outDir,f));removed++}
  }
}
const sorted=Object.fromEntries(Object.entries(index).sort((a,b)=>a[0].localeCompare(b[0])))
writeFileSync(
  indexPath,
  `/** auto-generated by scripts/build-spec-chunks.mjs — 规格 code → 内容哈希（规格本体在 public/spec/） */\nexport default ${JSON.stringify(sorted)}\n`
)
console.log(JSON.stringify({
  specs:Object.keys(index).length,unusedSkipped:(specData.specs||[]).length-Object.keys(index).length,
  removed,totalKB:Math.round(bytes/1024),maxKB:Math.round(max/1024),
}))
