/**
 * 在 catalog 流水线末尾再应用 mapOverrides.manual.json（优先级高于 structure-code / subclass 纠错）。
 * 不覆盖已成功接管的 structure-spec。
 */
import {readFileSync,writeFileSync,existsSync} from 'node:fs'
import {join,dirname} from 'node:path'
import {fileURLToPath} from 'node:url'

const root=join(dirname(fileURLToPath(import.meta.url)),'..')
const manualPath=join(root,'src','catalog','mapOverrides.manual.json')
const presetsPath=join(root,'src','catalog','presets.js')

if(!existsSync(manualPath)){
  console.log(JSON.stringify({skipped:true,reason:'no manual overrides'}))
  process.exit(0)
}

const manual=JSON.parse(readFileSync(manualPath,'utf8'))
const raw=readFileSync(presetsPath,'utf8')
const data=JSON.parse(raw.replace(/^\/\*\*[\s\S]*?\*\/\s*export\s+default\s+/,'').trim())
const byNum=Object.fromEntries((data.presets||[]).map(p=>[String(p.sourceNum),p]))

let applied=0,skippedSpec=0,missing=0
for(const [num,tid] of Object.entries(manual)){
  if(!tid)continue
  const p=byNum[String(num)]
  if(!p){missing++;continue}
  if(p.templateSource==='structure-spec'||p.templateSource==='structure-spec-takeover'){skippedSpec++;continue}
  if(p.templateId===tid)continue
  p.templateId=tid
  p.templateSource='map-override-manual'
  applied++
}

const byTemplate={},byCategory={}
let mapped=0
for(const p of data.presets||[]){
  if(p.templateId)mapped++
  byTemplate[p.templateId||'unmapped']=(byTemplate[p.templateId||'unmapped']||0)+1
  byCategory[p.categoryId]=(byCategory[p.categoryId]||0)+1
}
data.mapped=mapped
data.byTemplate=byTemplate
data.byCategory=byCategory
if(Array.isArray(data.categories)){
  data.categories=data.categories.map(c=>({...c,count:byCategory[c.id]||0}))
}

writeFileSync(
  presetsPath,
  `/** auto-generated by scripts/build-presets-from-csv.mjs — do not edit */\nexport default ${JSON.stringify(data,null,2)}\n`
)
console.log(JSON.stringify({applied,skippedSpec,missing,mapped},null,2))
