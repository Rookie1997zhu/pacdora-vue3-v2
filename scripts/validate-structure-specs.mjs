/**
 * 结构规格有效尺寸范围校验：对每个 spec-* 模板按默认/最小/最大跑与 check-templates 相同的断言。
 * 失败则逐档收窄 limits（相对默认尺寸的倍率）；默认尺寸都不过的规格剔除。结果回写 structureSpecs.js。
 * 由 build-structure-specs.mjs 在编译后调用（独立进程，保证加载新生成的规格）。
 */
import {readFileSync,writeFileSync,appendFileSync} from 'node:fs'
import {join,dirname} from 'node:path'
import {fileURLToPath} from 'node:url'
import {createKnife} from '../src/knife.js'
import {assertStableTopology} from '../src/knifeContract.js'
import {TEMPLATES} from '../src/templates/index.js'
import specData from '../src/catalog/structureSpecs.js'
import {assertKnife,sizeCases} from './lib/assertKnife.mjs'
import {measure,sampleInput,loadPresets} from './check-pacdora-fidelity.mjs'
import {createGeomResolver} from './lib/presetGeom.mjs'

const root=join(dirname(fileURLToPath(import.meta.url)),'..')
const outPath=join(root,'src','catalog','structureSpecs.js')
const reportPath=join(root,'未映射名单','17_结构规格编译.csv')

/** 相对默认尺寸的倍率档位，从宽到窄 */
const TIERS=[[.6,2],[.8,1.5],[.9,1.2],[.95,1.1],[.98,1.05]]

function limitsFor(def,[lo,hi]){
  // 样本上为 0 的尺寸（圆盒的宽、平面件的高）刀版不使用：给一个什么值都能过的宽区间，否则会算出下限大于上限的区间
  const r=v=>(Number(v)>0?[Math.max(10,Math.round(v*lo)),Math.max(Math.round(v*lo)+1,Math.round(v*hi))]:[0,2000])
  return {length:r(def.length),width:r(def.width),height:r(def.height)}
}

/** 用候选 limits 跑三档断言；多件时遍历全部 piece id。返回失败原因或 null */
function tryLimits(t,limits){
  const probe={...t,limits}
  const pieceIds=(t.supportsPiece&&Array.isArray(t.pieces)&&t.pieces.length)
    ?t.pieces.map(p=>p.id)
    :(t.supportsPiece?['bottom','lid']:[undefined])
  try{
    for(const piece of pieceIds){
      const knives={}
      for(const [label,dims] of Object.entries(sizeCases(probe))){
        knives[label]=createKnife({templateId:t.id,...dims,piece})
        assertKnife(probe,label+(piece?`/${piece}`:''),knives[label])
      }
      assertStableTopology(knives.default,knives.min)
      assertStableTopology(knives.default,knives.max)
    }
    return null
  }catch(e){
    return String(e?.message||e).split('\n')[0]
  }
}

const geomFileOf=createGeomResolver(root,loadPresets())

/**
 * 内部切线（sl）取舍：在金样尺寸下分别带/不带 sl 生成，切线总长更接近金样才保留。
 * 金样里相邻面片共边、但生成时两片各自内收留缝的地方，并集轮廓已经画出两条边，再加 sl 会重复。
 * 规格对象与注册表里的模板共用同一份 faces，直接摘掉 sl 即可对比。
 */
function settleSlits(spec,templateId){
  const faces=(spec.faces||[]).filter(f=>Array.isArray(f.sl)&&f.sl.length)
  if(!faces.length)return null
  const file=geomFileOf(spec.sampleNum)
  if(!file)return null
  let geom
  try{geom=JSON.parse(readFileSync(file,'utf8'))}catch{return null}
  const input=sampleInput(geom)
  const withSl=measure(templateId,geom,input)
  const saved=faces.map(f=>f.sl)
  for(const f of faces)delete f.sl
  const without=measure(templateId,geom,input)
  const keep=!withSl.error&&withSl.valid&&(without.error||withSl.cutErr<without.cutErr-.002)
  if(keep){
    faces.forEach((f,i)=>{f.sl=saved[i]})
    return 'slits-kept'
  }
  return 'slits-dropped'
}

const kept=[]
const notes=[]
let slitsKept=0,slitsDropped=0
for(const spec of specData.specs||[]){
  const t=TEMPLATES[`spec-${spec.code}`]
  let chosen=null,lastErr='template missing'
  if(t){
    // createKnife 读取注册表里的 limits；逐档替换后再测
    for(const tier of TIERS){
      const limits=limitsFor(spec.defaults,tier)
      t.limits=limits
      lastErr=tryLimits(t,limits)
      if(!lastErr){chosen={limits,tier};break}
    }
  }
  if(!chosen){
    notes.push([spec.code,spec.sampleNum,'','invalid',JSON.stringify(lastErr)])
    continue
  }
  t.limits=chosen.limits
  const slitVerdict=settleSlits(spec,t.id)
  if(slitVerdict==='slits-kept')slitsKept++
  else if(slitVerdict==='slits-dropped')slitsDropped++
  kept.push({...spec,limits:chosen.limits})
  if(chosen.tier!==TIERS[0])notes.push([spec.code,spec.sampleNum,'','narrowed',`x${chosen.tier.join('~')}`])
}

writeFileSync(
  outPath,
  `/** auto-generated by scripts/build-structure-specs.mjs — 结构规格（公式+图元，无刀版坐标） */\nexport default ${JSON.stringify({...specData,specs:kept})}\n`
)
if(notes.length)appendFileSync(reportPath,'\n'+notes.map(r=>r.join(',')).join('\n'),'utf8')
console.log(JSON.stringify({validated:kept.length,dropped:(specData.specs||[]).length-kept.length,narrowed:notes.filter(n=>n[3]==='narrowed').length,slitsKept,slitsDropped},null,2))
